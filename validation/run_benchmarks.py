def run(sizes: list[int], node_limit: int) -> dict:
    results: dict = {}
    for scen, kw in SCENARIOS.items():
        for size in sizes:
            rows = []
            for name in SAMPLES:
                rows.append(synthetic_experiment(sample_array(name), size, size, ALGOS, node_limit=node_limit, **kw))
            results[(scen, size)] = rows
    return results


def table(results: dict, sizes: list[int]) -> str:
    out = []
    for scen in SCENARIOS:
        out.append(f"\n### {scen}\n")
        out.append("| n | match acc. | " + " | ".join(f"{a} acc. / ms" for a in ALGOS) + " |")
        out.append("|---|---|" + "---|" * len(ALGOS))
        for size in sizes:
            rows = results[(scen, size)]
            macc = statistics.mean(r["match"]["match_accuracy"] for r in rows)
            cells = []
            for a in ALGOS:
                acc = statistics.mean(r["runs"][a]["neighbour_accuracy"] for r in rows)
                ms = statistics.mean(r["runs"][a]["elapsed_ms"] for r in rows)
                trunc = any(r["runs"][a]["truncated"] for r in rows)
                cells.append(f"{acc:.0%} / {ms:.1f}{'*' if trunc else ''}")
            out.append(f"| {size * size} | {macc:.0%} | " + " | ".join(cells) + " |")
    return "\n".join(out)


