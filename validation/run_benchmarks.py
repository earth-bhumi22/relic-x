    # --- A. node count vs n on seeded random compatibility tables (2 x k strips, no rotation) ------------------
    out += [
        f"\n### A. Node count vs n (random tables, 2×k grid, density 0.35, mean over {tables} seeds)\n",
        "| n | cells | unbounded tree | nodes, no incumbent | pruned | ms | nodes, greedy incumbent | pruned | ms | truncated (no inc. / inc.) |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    rec = {}
    for k in cols_list:
        n = 2 * k
        ids = [f"F{i:02d}" for i in range(n)]
        rows_ = []
        for sd in range(tables):
            compat = _random_compat(ids, random.Random(1000 * k + sd), 0.35)
            a, ta = _bt_run(ids, compat, 2, k, node_limit, False)
            b, tb = _bt_run(ids, compat, 2, k, node_limit, True)
            rows_.append((a, ta, b, tb))
        rec[n] = rows_

        def m(f, rows_=rows_):
            return statistics.mean(f(r) for r in rows_)

        trunc = (sum(r[0].truncated for r in rows_), sum(r[2].truncated for r in rows_))
        out.append(
            f"| {n} | {n} | {_perm_tree_size(n):,} | {m(lambda r: r[0].meta['nodes']):,.0f}{'*' if trunc[0] else ''} "
            f"| {m(lambda r: r[0].meta['pruned']):,.0f} | {m(lambda r: r[1]):.1f} "
            f"| {m(lambda r: r[2].meta['nodes']):,.0f}{'*' if trunc[1] else ''} | {m(lambda r: r[2].meta['pruned']):,.0f} "
            f"| {m(lambda r: r[3]):.1f} | {trunc[0]}/{tables} / {trunc[1]}/{tables} |"
        )
    # growth fit over the sizes where no run was truncated (so the counts are exact search sizes)
    fits = []
    for label, idx in (("no incumbent", 0), ("greedy incumbent", 2)):
        pts = [
            (n, statistics.mean(r[idx].meta["nodes"] for r in rows_))
            for n, rows_ in rec.items()
            if not any(r[idx].truncated for r in rows_)
        ]
        if len(pts) >= 3:
            s, _i, r2 = linear_fit([p[0] for p in pts], [float(np.log(p[1])) for p in pts])
            fits.append(
                f"- {label}: ln(nodes) vs n over n = {pts[0][0]}…{pts[-1][0]} ({len(pts)} un-truncated sizes): "
                f"slope **{s:.3f}** (each extra fragment multiplies the search by ×{np.exp(s):.2f}), R² = {r2:.3f}."
            )
        else:
            fits.append(f"- {label}: fewer than 3 un-truncated sizes, no fit.")
    first_trunc = next((n for n, rows_ in rec.items() if any(r[0].truncated for r in rows_)), None)
    out += [
        "\n" + "\n".join(fits),
        f"- Smallest n where at least one no-incumbent run was truncated: {first_trunc if first_trunc else 'none in this range'}."
        "\n",
    ]
    n_all = sorted(rec)
    (HERE / "backtracking_nodes.svg").write_text(
        svg_chart(
            f"Search nodes vs n (limit {node_limit:,})",
            "fragments n",
            "nodes",
            [
                {
                    "name": "no incumbent",
                    "points": [(n, statistics.mean(r[0].meta["nodes"] for r in rec[n])) for n in n_all],
                    "line": True,
                },
                {
                    "name": "greedy incumbent",
                    "points": [(n, statistics.mean(r[2].meta["nodes"] for r in rec[n])) for n in n_all],
                    "line": True,
                },
                {"name": f"node limit {node_limit:,}", "points": [(n, node_limit) for n in n_all], "line": True},
                {
                    "name": "pruned (incumbent)",
                    "points": [(n, statistics.mean(r[2].meta["pruned"] for r in rec[n])) for n in n_all],
                    "line": True,
                },
            ],
        )
    )
    (HERE / "backtracking_time.svg").write_text(
        svg_chart(
            "Backtracking time vs n",
            "fragments n",
            "time (ms)",
            [
                {"name": "no incumbent", "points": [(n, statistics.mean(r[1] for r in rec[n])) for n in n_all], "line": True},
                {
                    "name": "greedy incumbent",
                    "points": [(n, statistics.mean(r[3] for r in rec[n])) for n in n_all],
                    "line": True,
                },
            ],
        )
    )
    out.append("![nodes vs n](backtracking_nodes.svg)\n\n![time vs n](backtracking_time.svg)\n")

    # --- B. greedy vs backtracking on synthetic images -----------------------------------------------------------
    sizes = [2, 3] if quick else [2, 3, 4]
    seeds = [1] if quick else [1, 2]
    scenarios = {"clean": (0.0, 0.0), "damaged (noise 4, erosion 0.3)": (4.0, 0.3)}
    out += [
        f"\n### B. Backtracking vs greedy on synthetic images (mean over {len(SAMPLES)} samples × seeds {seeds}, no rotation)\n",
        "`score gap` = backtracking total score − greedy total score (≥ 0 always, because greedy is the incumbent). "
        "Accuracy is neighbour / direct against the known truth. **\\*** = at least one run truncated.\n",
    ]
    for scen, (noise, erosion) in scenarios.items():
        out += [
            f"\n**{scen}**\n",
            "| n | greedy score | backtracking score | score gap | greedy nbr / direct | backtracking nbr / direct | nodes (inc.) | truncated runs | improved on greedy |",
            "|---|---|---|---|---|---|---|---|---|",
        ]
        for size in sizes:
            recs = []
            for s in SAMPLES:
                for sd in seeds:
                    ids, match, truth = prepared(s, size, noise, erosion, sd)
                    compat = compat_table(match.matches)
                    g = solve_greedy(ids, compat, size, size)
                    bt, _ = _bt_run(ids, compat, size, size, node_limit, True)
                    recs.append((g, bt, evaluate(g, truth), evaluate(bt, truth)))
            mean_ = lambda f: statistics.mean(f(r) for r in recs)  # noqa: E731
            tr = sum(r[1].truncated for r in recs)
            imp = sum(r[1].total_score > r[0].total_score + 1e-9 for r in recs)
            out.append(
                f"| {size * size} | {mean_(lambda r: r[0].total_score):.3f} | {mean_(lambda r: r[1].total_score):.3f} "
                f"| {mean_(lambda r: r[1].total_score - r[0].total_score):+.3f} "
                f"| {mean_(lambda r: r[2]['neighbour_accuracy']):.0%} / {mean_(lambda r: r[2]['direct_accuracy']):.0%} "
                f"| {mean_(lambda r: r[3]['neighbour_accuracy']):.0%} / {mean_(lambda r: r[3]['direct_accuracy']):.0%} "
                f"| {mean_(lambda r: r[1].meta['nodes']):,.0f}{'*' if tr else ''} | {tr}/{len(recs)} | {imp}/{len(recs)} |"
            )

    # --- C. row DP vs backtracking on 2 x n -----------------------------------------------------------------------
    dp_cols = [2, 3, 4, 5, 6] if quick else [2, 3, 4, 5, 6, 7, 8]
    max_states = 1_500_000
    out += [
        "\n### C. Row-profile DP vs backtracking on 2×c strips (random tables, density 0.35, seed 7, no rotation)\n",
        f"DP state limit for this table: {max_states:,} stored states (`solve_row_dp(max_states=…)`). "
        "`transitions` counts DP edge relaxations; backtracking `nodes` is with the greedy incumbent and "
        f"limit {node_limit:,}. Scores agree whenever backtracking is not truncated.\n",
        "| c | fragments | DP states stored | DP transitions | DP ms | backtracking nodes | backtracking ms | DP score | backtracking score |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    dp_pts, bt_pts = [], []
    for c in dp_cols:
        n = 2 * c
        ids = [f"F{i:02d}" for i in range(n)]
        compat = _random_compat(ids, random.Random(7), 0.35)
        bt, bms = _bt_run(ids, compat, 2, c, node_limit, True)
        try:
            t0 = time.perf_counter()
            dp = solve_row_dp(ids, compat, c, False, max_states=max_states)
            dms = (time.perf_counter() - t0) * 1000
            dp_cells = (
                f"{dp.meta['states_stored']:,} | {dp.operations.get('dp_transitions', 0):,} | {dms:.0f}",
                f"{dp.total_score:.3f}",
            )
            dp_pts.append((n, dms))
        except ValueError as e:
            dp_cells = (f"— ({e}) | — | —", "—")
        bt_pts.append((n, bms))
        out.append(
            f"| {c} | {n} | {dp_cells[0]} | {bt.meta['nodes']:,}{'*' if bt.truncated else ''} | {bms:.0f} "
            f"| {dp_cells[1]} | {bt.total_score:.3f} |"
        )
    (HERE / "row_dp_vs_backtracking.svg").write_text(
        svg_chart(
            "Time: row DP vs backtracking (2×c)",
            "fragments n",
            "time (ms)",
            [
                {"name": "row DP", "points": dp_pts, "line": True},
                {"name": "backtracking (inc.)", "points": bt_pts, "line": True},
            ],
        )
    )
    out += ["\n![DP vs backtracking](row_dp_vs_backtracking.svg)\n", BT_END, ""]
    return "\n".join(out)


