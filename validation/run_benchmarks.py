_PREP: dict = {}


def prepared(sample: str, size: int, noise: float, erosion: float, seed: int):
    """Fragment, match and cache one synthetic instance (unrotated) so every solver sees the same matches."""
    key = (sample, size, noise, erosion, seed)
    if key not in _PREP:
        frag = fragment_image(sample_array(sample), size, size, rotate=False, noise=noise, erosion=erosion, seed=seed)
        cfg = MatchConfig()
        feats, truth = {}, {}
        for k, f in enumerate(frag.fragments):
            fid = f"F{k + 1:02d}"
            feats[fid] = extract_features(f.pixels, cfg.strip_len, cfg.levels, cfg.depth)
            truth[fid] = Truth(f.true_row, f.true_col, f.scramble_rot)
        _PREP[key] = (list(feats), match_all(feats, cfg), truth)
    return _PREP[key]


def solve_instance(sample: str, size: int, noise: float, erosion: float, seed: int) -> dict:
    ids, match, truth = prepared(sample, size, noise, erosion, seed)
    out = {}
    for name, params in VARIANTS.items():
        res = run_solver(ids, match, size, size, False, params)
        ops = res.operations
        out[name] = {
            **evaluate(res, truth),
            "ms": res.elapsed_ms,
            "score": res.total_score,
            "score_lookups": ops.get("score_lookups", 0),
            "heap_pushes": ops.get("heap_pushes", 0),
            "heap_pops": ops.get("heap_pops", 0),
            "conflicts": res.meta.get("conflicts", 0),
            "fallbacks": sum(t["action"] == "fallback" for t in res.trace) + res.trace_dropped.get("fallback", 0),
            "edges": len(build_graph(ids, match.matches, threshold=params.threshold, top_k=params.top_k).edges),
        }
    return out


def loglog_fit(xs, ys) -> tuple[float, float]:
    """Slope and R² of log y against log x (growth exponent)."""
    slope, _intercept, r2 = linear_fit(np.log(np.asarray(xs, float)), np.log(np.asarray(ys, float)))
    return slope, r2


