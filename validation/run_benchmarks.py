def _p(v: float) -> str:
    return f"{v * 100:.0f}%"


def sv_findings(idx: SvIndex, meta: dict) -> list[str]:
    """Headline findings, written from the numbers (nothing typed in by hand)."""
    big, sizes = max(meta["sizes"]), meta["sizes"]
    n = big * big
    out = []
    # 1. accuracy ranking at the largest n, damaged
    stats = {a: idx.get("damaged", big, a) for a in ALGOS}
    cells = {a: (s["neighbour_accuracy_mean"], s["neighbour_accuracy_sd"], s["n_runs"]) for a, s in stats.items()}
    order = sorted(ALGOS, key=lambda a: -cells[a][0])
    win = clear_winner(cells)
    listing = ", ".join(f"{SV_SHORT[a]} {pct_cell(cells[a][0], cells[a][1])}" for a in order)
    verdict = (
        f"**{SV_SHORT[win]}** is clearly ahead (its 95 % interval lies above every other solver's)."
        if win
        else "The spread does **not** support a single winner: the top intervals overlap, so no ranking is claimed."
    )
    out.append(
        f"Accuracy, `damaged`, n = {n}: {listing}. {verdict} *(table: `damaged` neighbour accuracy; chart: accuracy vs. n)*"
    )
    # 2. cost
    g, b, d = (idx.get("damaged", big, a) for a in ("greedy", "best_first", "dijkstra"))
    out.append(
        f"Cost, `damaged`, n = {n}: greedy {g['elapsed_ms_mean']:.2f} ms and {g['operations_total_mean']:,.0f} operations, "
        f"best-first {b['elapsed_ms_mean']:.2f} ms and {b['operations_total_mean']:,.0f}, Dijkstra {d['elapsed_ms_mean']:.2f} ms "
        f"and {d['operations_total_mean']:,.0f}; greedy does {g['operations_total_mean'] / b['operations_total_mean']:.1f}× the "
        "operations of best-first. *(tables: operations, time; charts: time and operations vs. n)*"
    )
    # 3. truncation
    first = next((s for s in sizes if idx.get("damaged", s, "backtracking")["n_truncated"] > 0), None)
    bt = idx.get("damaged", big, "backtracking")
    if first is None:
        out.append(f"Backtracking finished every `damaged` run inside the node limit up to n = {n}.")
    else:
        out.append(
            f"Backtracking is measurable only for small n: it first hits the node limit ({meta['node_limit']:,}) at n = {first * first} "
            f"(`damaged`) and at n = {n} {bt['n_truncated']} of {bt['n_runs']} runs are truncated, so its time there "
            f"({bt['elapsed_ms_mean']:.0f} ms) is the cost of the limit, not of solving. *(table: truncated vs. complete runs)*"
        )
    # 4. oracle
    rr = {a: idx.get("damaged", big, a)["neighbour_accuracy_mean"] for a in ALGOS}
    oo = {a: idx.get("damaged", big, a, "oracle")["neighbour_accuracy_mean"] for a in ALGOS}
    macc = idx.get("damaged", big, "greedy")["match_accuracy_mean"]
    out.append(
        f"Matcher vs. solver, `damaged`, n = {n}: the matcher's top choice is right for {_p(macc)} of true adjacencies. With the "
        "ground-truth adjacency instead of the matcher, neighbour accuracy goes "
        + ", ".join(f"{SV_SHORT[a]} {_p(rr[a])} → {_p(oo[a])}" for a in ALGOS)
        + ". The gap to 100 % in the oracle figure is lost by the solver; the rise from real to oracle is lost by the matcher. "
        "*(table: oracle)*"
    )
    return out


def sv_fit_notes(idx: SvIndex, sizes: list[int]) -> list[str]:
    """One sentence per solver comparing the fitted operations exponent with the derivation."""
    expect = {"greedy": (2.5, 3.0), "best_first": (1.6, 2.6), "dijkstra": (1.0, None)}  # (estimate, hard bound)
    big = max(sizes)

    def lookup_share(a):
        s = idx.get("damaged", big, a)
        return s["score_lookups_mean"] / s["operations_total_mean"]

    why = {
        "greedy": "the frontier of a compact layout is smaller or larger than the √t used in the estimate, and the n range is short",
        "best_first": f"score_lookups (fallback placement of fragments the pruned graph leaves unattached) are {lookup_share('best_first'):.0%} of its operations at n = {big * big}, on top of the heap work",
        "dijkstra": f"score_lookups (fallback placement of fragments the top-3 graph does not reach) are {lookup_share('dijkstra'):.0%} of its operations at n = {big * big}, which grow faster than the (V + E) log V core",
    }
    out = []
    for a in ("greedy", "best_first", "dijkstra"):
        f = sv_fit(idx, "damaged", a, sizes, "operations_total")
        est, bound = expect[a]
        if f is None:
            out.append(f"- **{SV_SHORT[a]}**: too few usable points for a fit.")
            continue
        k, r2, _ = f
        within = "" if bound is None else f" and respects the bound n^{bound:g}"
        if bound is not None and k > bound + 0.05:
            msg = f"is **above** the derived upper bound n^{bound:g}; this contradicts the derivation and needs investigating"
        elif abs(k - est) <= 0.25:
            msg = f"agrees with the estimate of about n^{est:g}{within}"
        else:
            hold = "" if bound is None else f" (the bound n^{bound:g} still holds)"
            msg = f"**differs** from the estimate of about n^{est:g}{hold}; likely reason: {why[a]}"
        out.append(f"- **{SV_SHORT[a]}**: operations grow as n^{k:.2f} (R² {r2:.3f}); this {msg}.")
    bt_sizes = [s for s in sizes if idx.get("damaged", s, "backtracking")["n_truncated"] == 0]
    if bt_sizes:
        lo, hi = bt_sizes[0], bt_sizes[-1]
        a, z = idx.get("damaged", lo, "backtracking"), idx.get("damaged", hi, "backtracking")
        out.append(
            f"- **Backtracking**: complete only for n = {lo * lo}…{hi * hi}, where its nodes go from {a['operations_total_mean']:,.0f} "
            f"to {z['operations_total_mean']:,.0f} operations; beyond that the node limit caps the cost, so a power-law fit is "
            "not meaningful and exponential growth is shown by the node counts of the T17 section instead."
        )
    out.append("")
    return out


