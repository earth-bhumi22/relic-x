def solve_instance_dj(sample: str, size: int, noise: float, erosion: float, seed: int) -> dict:
    """Run greedy, best-first and Dijkstra (as the API runs it: mutual top-3 graph; and on the full graph)."""
    ids, match, truth = prepared(sample, size, noise, erosion, seed)
    compat = compat_table(match.matches)
    full = build_graph(ids, match.matches)
    results = {
        "greedy": (run_solver(ids, match, size, size, False, SolveParams("greedy")), None),
        "best_first": (run_solver(ids, match, size, size, False, SolveParams("best_first")), full),
        "dijkstra top-3": (
            run_solver(ids, match, size, size, False, SolveParams("dijkstra")),
            build_graph(ids, match.matches, top_k=3),
        ),
        "dijkstra full": (solve_dijkstra(ids, compat, full, size, size, False), full),
    }
    out = {}
    for name, (res, g) in results.items():
        ops = res.operations
        out[name] = {
            **evaluate(res, truth),
            "ms": res.elapsed_ms,
            "heap_pops": ops.get("heap_pops", 0),
            "relaxations": ops.get("relaxations", 0),
            "score_lookups": ops.get("score_lookups", 0),
            "conflicts": res.meta.get("conflicts", 0),
            "unreachable": res.meta.get("unreachable", 0),
            "edges": len(g.edges) if g is not None else 0,
        }
    # tree quality on the full graph: mean weight of the shortest-path-tree edges vs. the maximum spanning tree
    seed_id = pick_seed(ids, compat)
    _, parent, order = dijkstra(full, seed_id)
    spt = [full.adj[parent[v]][v].weight for v in order[1:]]
    out["tree"] = {
        "spt_mean": statistics.mean(spt) if spt else 1.0,
        "mst_mean": mst_mean_weight(full, set(order)),
        "spt_parent_differs": sum(1 for v in order[1:] if parent[v] != prim_parent(full, order, v)) / max(1, len(spt)),
    }
    return out


def mst_edges(g: FragmentGraph, nodes: set[str]):
    """Kruskal maximum spanning forest restricted to ``nodes`` (the oracle for Prim's tree)."""
    parent = {n: n for n in nodes}

    def find(x):
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    chosen = []
    for e in sorted((e for e in g.edges if e.u in nodes), key=lambda e: (-e.weight, e.u, e.v)):
        ru, rv = find(e.u), find(e.v)
        if ru != rv:
            parent[ru] = rv
            chosen.append(e)
    return chosen


def mst_mean_weight(g: FragmentGraph, nodes: set[str]) -> float:
    es = mst_edges(g, nodes)
    return statistics.mean(e.weight for e in es) if es else 1.0


def prim_parent(g: FragmentGraph, order: list[str], v: str):
    """Parent of v in the maximum spanning tree rooted at order[0] (computed by a plain Prim, ties by id)."""
    key = ("prim", id(g), order[0])
    if key not in _PRIM_CACHE:
        import heapq

        par, seen, pq = {order[0]: None}, set(), [(0.0, order[0], None)]
        while pq:
            negw, u, p = heapq.heappop(pq)
            if u in seen:
                continue
            seen.add(u)
            par[u] = p
            for x, e in g.adj[u].items():
                if x not in seen:
                    heapq.heappush(pq, (-e.weight, x, u))
        _PRIM_CACHE.clear()
        _PRIM_CACHE[key] = par
    return _PRIM_CACHE[key][v]


