def _grid_score(arr, rows, cols, c) -> float:
    total = 0.0
    for r in range(rows):
        for k in range(cols):
            f = arr[r * cols + k]
            if k + 1 < cols:
                total += c.get((f, 1, arr[r * cols + k + 1], 3), 0.0)
            if r + 1 < rows:
                total += c.get((f, 2, arr[(r + 1) * cols + k], 0), 0.0)
    return total


def _random_compat(ids, rng, density=0.35):
    c = {}
    for a, b in itertools.combinations(ids, 2):
        for sa in range(4):
            for sb in range(4):
                if rng.random() < density:
                    c[(a, sa, b, sb)] = c[(b, sb, a, sa)] = rng.random()
    return c


def _graph_from_compat(ids, compat):
    return build_graph(
        ids, [SideMatch(a, sa, b, sb, w, w, w, w, w, w) for (a, sa, b, sb), w in compat.items() if a < b]
    )


def _layout_str(placements) -> str:
    cells = {(p.row, p.col): p.fragment for p in placements}
    rows, cols = max(r for r, _ in cells) + 1, max(c for _, c in cells) + 1
    return " / ".join(" ".join(cells.get((r, c), ".") for c in range(cols)) for r in range(rows))


def tiny_grid_optimality(rows: int, cols: int, tables: int) -> dict:
    ids = [f"F{i}" for i in range(rows * cols)]
    hit = {"greedy": 0, "best_first": 0}
    ratio: dict = {"greedy": [], "best_first": []}
    used = 0
    for seed in range(tables):
        compat = _random_compat(ids, random.Random(seed))
        opt = max(_grid_score(p, rows, cols, compat) for p in itertools.permutations(ids))
        if opt <= 0:
            continue
        used += 1
        scores = {
            "greedy": solve_greedy(ids, compat, rows, cols).total_score,
            "best_first": solve_best_first(ids, compat, _graph_from_compat(ids, compat), rows, cols).total_score,
        }
        for nm, sc in scores.items():
            hit[nm] += sc >= opt - 1e-3
            ratio[nm].append(sc / opt)
    return {
        "tables": used,
        "greedy_hit": hit["greedy"] / used,
        "best_first_hit": hit["best_first"] / used,
        "greedy_ratio": statistics.mean(ratio["greedy"]),
        "best_first_ratio": statistics.mean(ratio["best_first"]),
    }


def counterexample() -> dict:
    ids = list("ABCD")
    c: dict = {}
    for a, b, w in (("B", "A", 0.15), ("D", "A", 0.6)):  # b is right of a
        c[(a, 1, b, 3)] = c[(b, 3, a, 1)] = w
    for a, b, w in (("C", "B", 0.85), ("D", "A", 0.05), ("D", "C", 0.8)):  # b is below a
        c[(a, 2, b, 0)] = c[(b, 0, a, 2)] = w
    gr = solve_greedy(ids, c, 2, 2)
    bf = solve_best_first(ids, c, _graph_from_compat(ids, c), 2, 2)
    best = max(itertools.permutations(ids), key=lambda p: _grid_score(p, 2, 2, c))
    return {
        "greedy": gr.total_score,
        "greedy_layout": _layout_str(gr.placements),
        "best_first": bf.total_score,
        "best_first_layout": _layout_str(bf.placements),
        "optimum": _grid_score(best, 2, 2, c),
        "optimum_layout": f"{best[0]} {best[1]} / {best[2]} {best[3]}",
    }


def replace_section(text: str, begin: str, end: str, report: str) -> str:
    if begin in text:
        head, rest = text.split(begin, 1)
        tail = rest.split(end, 1)[1].lstrip("\n") if end in rest else ""
        return head + report + tail
    return text.rstrip("\n") + "\n\n" + report


