"""Solver benchmark: accuracy, time and operation counts vs. fragment count.

Owner: A (Arvind) — extended in issue T32.

    cd backend && pip install -e .
    python ../validation/run_benchmarks.py            # writes validation/results.md
    python ../validation/run_benchmarks.py --quick    # 3x3 and 4x4 only

Every number comes from synthetic fragmentation of the bundled samples, so the
ground truth is known. Seeds are fixed: re-running gives the same tables.
"""

from __future__ import annotations

import argparse
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "backend" / "src"))

from relicx.engine import synthetic_experiment  # noqa: E402
from relicx.samples import SAMPLES, sample_array  # noqa: E402

ALGOS = ["greedy", "best_first", "dijkstra", "backtracking"]
SCENARIOS = {
    "clean": dict(rotate=False, noise=0.0, erosion=0.0),
    "damaged": dict(rotate=False, noise=4.0, erosion=0.3),
    "damaged + rotation": dict(rotate=True, noise=4.0, erosion=0.3),
}


def run(sizes: list[int], node_limit: int) -> dict:
    results: dict = {}
    for scen, kw in SCENARIOS.items():
        for size in sizes:
            rows = []
            for name in SAMPLES:
                rows.append(synthetic_experiment(sample_array(name), size, size, ALGOS, node_limit=node_limit, **kw))
            results[(scen, size)] = rows
    return results


def table(results: dict, sizes: list[int]) -> str:
    out = []
    for scen in SCENARIOS:
        out.append(f"\n### {scen}\n")
        out.append("| n | match acc. | " + " | ".join(f"{a} acc. / ms" for a in ALGOS) + " |")
        out.append("|---|---|" + "---|" * len(ALGOS))
        for size in sizes:
            rows = results[(scen, size)]
            macc = statistics.mean(r["match"]["match_accuracy"] for r in rows)
            cells = []
            for a in ALGOS:
                acc = statistics.mean(r["runs"][a]["neighbour_accuracy"] for r in rows)
                ms = statistics.mean(r["runs"][a]["elapsed_ms"] for r in rows)
                trunc = any(r["runs"][a]["truncated"] for r in rows)
                cells.append(f"{acc:.0%} / {ms:.1f}{'*' if trunc else ''}")
            out.append(f"| {size * size} | {macc:.0%} | " + " | ".join(cells) + " |")
    return "\n".join(out)


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--quick", action="store_true")
    p.add_argument("--node-limit", type=int, default=50_000)
    args = p.parse_args()
    sizes = [3, 4] if args.quick else [3, 4, 5, 6]
    results = run(sizes, args.node_limit)
    body = f"""# RELIC-X — validation results

Generated by `validation/run_benchmarks.py` (node limit {args.node_limit:,}). Each cell is the mean over
the three bundled samples ({", ".join(SAMPLES)}). **acc.** = neighbour accuracy (share of true
adjacent pairs reconstructed correctly); **ms** = solver time only (matching excluded);
**\\*** = backtracking hit its node limit on at least one sample and returned its best-so-far.
{table(results, sizes)}

## Reading the tables

- Greedy scores each candidate against *all* placed neighbours, which makes it hard to beat on these inputs.
- Backtracking starts from the greedy solution and can only improve the total compatibility score.
  Higher score does not always mean higher accuracy when the matcher itself is wrong.
- Best-first (Prim) is the fastest; it trusts single strongest joins.
- Dijkstra minimises *path* cost from the seed, which is the wrong objective for assembly;
  it is kept as the comparison point (see docs/ALGORITHMS.md).

Owners: solver experiments **A**, matcher experiments **B** (T31, separate section to be added).
"""
    out = Path(__file__).with_name("results.md")
    out.write_text(body)
    print(body)


if __name__ == "__main__":
    main()
