def sv_write(cfg: SvConfig, out_dir: Path, progress: bool = True) -> tuple[str, list[dict], dict]:
    """Run the experiment, write the two CSVs, and return the T32 block (rendered from the CSV round trip, so the
    committed text can be regenerated from the committed CSVs alone)."""
    t0 = time.perf_counter()
    runs = sv_collect(cfg, progress)
    meta = sv_meta(cfg, time.perf_counter() - t0)
    out_dir.mkdir(parents=True, exist_ok=True)
