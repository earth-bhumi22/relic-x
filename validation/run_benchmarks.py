def dijkstra_counterexample() -> dict:
    ids = list("ABC")
    c: dict = {}
    for a, b, w in (("B", "A", 0.25), ("C", "B", 0.60)):  # b is right of a
        c[(a, 1, b, 3)] = c[(b, 3, a, 1)] = w
    c[("C", 2, "A", 0)] = c[("A", 0, "C", 2)] = 0.35  # A is below C
    g = _graph_from_compat(ids, c)
    dist, parent, order = dijkstra(g, "A")
    dj = solve_dijkstra(ids, c, g, 2, 2, seed="A")
    bf = solve_best_first(ids, c, g, 2, 2, seed="A")
    prim_b = next(t["parent"] for t in bf.trace if t["action"] == "place" and t["fragment"] == "B")
    cells = [(r, k) for r in range(2) for k in range(2)]
    best = 0.0
    for chosen in itertools.permutations(cells, 3):
        at = dict(zip(chosen, ids, strict=True))
        t = 0.0
        for (r, k), f in at.items():
            if (r, k + 1) in at:
                t += c.get((f, 1, at[(r, k + 1)], 3), 0.0)
            if (r + 1, k) in at:
                t += c.get((f, 2, at[(r + 1, k)], 0), 0.0)
        best = max(best, t)
    return {
        "settle": [(v, dist[v]) for v in order],
        "dij_parent": parent["B"],
        "prim_parent": prim_b,
        "dijkstra": dj.total_score,
        "dijkstra_layout": _layout_str(dj.placements),
        "best_first": bf.total_score,
        "best_first_layout": _layout_str(bf.placements),
        "optimum": best,
    }


