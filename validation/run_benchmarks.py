def _bt_run(ids, compat, rows, cols, node_limit, with_incumbent, rotation=False):
    inc = solve_greedy(ids, compat, rows, cols, rotation).placements if with_incumbent else None
    t0 = time.perf_counter()
    res = solve_backtracking(ids, compat, rows, cols, rotation, node_limit=node_limit, incumbent=inc)
    ms = (time.perf_counter() - t0) * 1000
    return res, ms


def _perm_tree_size(n: int) -> int:
    """Nodes of the un-bounded permutation tree (every ordered choice of distinct fragments), root included."""
    total, term = 1, 1
    for k in range(n):
        term *= n - k
        total += term
    return total


