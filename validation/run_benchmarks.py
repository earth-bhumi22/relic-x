def sv_fit(idx: SvIndex, scen: str, solver: str, sizes: list[int], field: str) -> tuple | None:
    """Log-log fit of the cell mean against n over the sizes where no run was truncated."""
    pts = [
        (s * s, idx.get(scen, s, solver)[f"{field}_mean"])
        for s in sizes
        if idx.get(scen, s, solver)["n_truncated"] == 0
    ]
    pts = [(n, v) for n, v in pts if v and v > 0]
    if len(pts) < 3:
        return None
    slope, r2 = loglog_fit([n for n, _ in pts], [v for _, v in pts])
    return slope, r2, len(pts)


