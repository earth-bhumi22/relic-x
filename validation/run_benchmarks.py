HERE = Path(__file__).parent
GRAPH_BEGIN, GRAPH_END = "<!-- T14:begin (generated by run_benchmarks.py) -->", "<!-- T14:end -->"
THRESHOLDS = [0.0, 0.2, 0.4, 0.5, 0.6, 0.7, 0.8, 0.9]
TOP_KS = [1, 2, 3, 4, 6, None]
FACING = {(-1, 0): 0, (0, 1): 1, (1, 0): 2, (0, -1): 3}  # (d_row, d_col) of the neighbour -> side index
COLORS = ["#2563eb", "#dc2626", "#16a34a", "#9333ea"]


def sample_matches(name: str, size: int):
    """Damaged (noise 4, erosion 0.3), unrotated size x size fragmentation of a sample, plus its ground truth."""
    frag = fragment_image(sample_array(name), size, size, rotate=False, noise=4.0, erosion=0.3, seed=7)
    cfg = MatchConfig()
    feats = {
        f"F{k + 1:02d}": extract_features(f.pixels, cfg.strip_len, cfg.levels, cfg.depth)
        for k, f in enumerate(frag.fragments)
    }
    pos = {f"F{k + 1:02d}": (f.true_row, f.true_col) for k, f in enumerate(frag.fragments)}
    return list(feats), match_all(feats, cfg).matches, pos


def is_true_edge(e, pos) -> bool:
    (r1, c1), (r2, c2) = pos[e.u], pos[e.v]
    side = FACING.get((r2 - r1, c2 - c1))
    return side is not None and e.side_u == side and e.side_v == (side + 2) % 4


def graph_stats(g: FragmentGraph, pos) -> dict:
    comps, _ = bfs_components(g)
    edges = g.edges
    return {
        "edges": len(edges),
        "true": sum(is_true_edge(e, pos) for e in edges),
        "components": len(comps),
        "largest": max((len(c) for c in comps), default=0),
    }


def cell(st: dict) -> str:
    share = f"{st['true'] / st['edges']:.0%}" if st["edges"] else "–"
    return f"{st['edges']} ({share}) / {st['components']} / {st['largest']}"


def edges_vs_threshold(size: int) -> tuple[str, dict]:
    true_pairs = size * (size - 1) * 2
    data = {name: sample_matches(name, size) for name in SAMPLES}
    out = [
        f"\n### Edges vs. threshold and top-k ({size}×{size} grid, damaged: noise 4, erosion 0.3, seed 7)\n",
        f"{size * size} fragments, **{true_pairs}** true adjacent pairs. Each cell: **edges (share that are true neighbours) / components / "
        "largest component**. Edges are the best side pairing per fragment pair after pruning.\n",
        "Threshold sweep (no top-k):\n",
        "| threshold | " + " | ".join(SAMPLES) + " |",
        "|---|" + "---|" * len(SAMPLES),
    ]
    thr_series = {n: [] for n in SAMPLES}
    for t in THRESHOLDS:
        cells = []
        for name, (ids, matches, pos) in data.items():
            st = graph_stats(build_graph(ids, matches, threshold=t), pos)
            thr_series[name].append((t, st["edges"]))
            cells.append(cell(st))
        out.append(f"| {t:.1f} | " + " | ".join(cells) + " |")
    out += [
        "\nMutual top-k sweep (threshold 0):\n",
        "| top-k | " + " | ".join(SAMPLES) + " |",
        "|---|" + "---|" * len(SAMPLES),
    ]
    for k in TOP_KS:
        cells = [cell(graph_stats(build_graph(ids, m, top_k=k), pos)) for ids, m, pos in data.values()]
        bound = f" (≤ {k * size * size // 2} edges)" if k else " (no pruning)"
        out.append(f"| {k if k else 'none'}{bound} | " + " | ".join(cells) + " |")
    chart = svg_chart(
        f"Graph edges vs. threshold ({size}×{size})",
        "threshold",
        "edges kept",
        [{"name": n, "points": pts, "line": True} for n, pts in thr_series.items()],
    )
    (HERE / "graph_threshold.svg").write_text(chart)
    out.append("\n![edges vs threshold](graph_threshold.svg)\n")
    return "\n".join(out), data


def random_graph(v: int, avg_degree: float, seed: int) -> FragmentGraph:
    rng = random.Random(seed)
    nodes = [f"N{i:06d}" for i in range(v)]
    pairs: set[tuple[int, int]] = set()
    target = int(v * avg_degree / 2)
    while len(pairs) < target:
        a, b = rng.randrange(v), rng.randrange(v)
        if a != b:
            pairs.add((min(a, b), max(a, b)))
    matches = [
        SideMatch(nodes[a], rng.randrange(4), nodes[b], rng.randrange(4), *([rng.random()] * 6))
        for a, b in sorted(pairs)
    ]
    return build_graph(nodes, matches)


def best_time_ms(fn, repeats: int = 5) -> float:
    best = float("inf")
    for _ in range(repeats):
        t0 = time.perf_counter()
        fn()
        best = min(best, time.perf_counter() - t0)
    return best * 1000


def linear_fit(xs, ys) -> tuple[float, float, float]:
    slope, intercept = np.polyfit(xs, ys, 1)
    pred = slope * np.asarray(xs) + intercept
    ss_res = float(np.sum((np.asarray(ys) - pred) ** 2))
    ss_tot = float(np.sum((np.asarray(ys) - np.mean(ys)) ** 2))
    return float(slope), float(intercept), 1 - ss_res / ss_tot


def dfs_peak_stack(g: FragmentGraph) -> tuple[int, list[str]]:
    """Instrumented replica of engine.dfs_components that also tracks the peak stack size."""
    seen: set[str] = set()
    order, peak = [], 0
    for s in sorted(g.nodes):
        if s in seen:
            continue
        stack = [s]
        while stack:
            peak = max(peak, len(stack))
            u = stack.pop()
            if u in seen:
                continue
            seen.add(u)
            order.append(u)
            nbrs = g.adj[u]
            for v in reversed(sorted(nbrs, key=lambda x: (-nbrs[x].weight, x))):
                if v not in seen:
                    stack.append(v)
    return peak, order


def bfs_peak_queue(g: FragmentGraph) -> int:
    seen: set[str] = set()
    peak = 0
    for s in sorted(g.nodes):
        if s in seen:
            continue
        q = deque([s])
        seen.add(s)
        while q:
            peak = max(peak, len(q))
            u = q.popleft()
            for v in g.adj[u]:
                if v not in seen:
                    seen.add(v)
                    q.append(v)
    return peak


def traversal_scaling(quick: bool) -> str:
    sizes = [1000, 2000, 4000, 8000] if quick else [1000, 2000, 4000, 8000, 16000, 32000, 64000]
    fixed_v, degrees = (4000, [2, 4, 8, 16]) if quick else (8000, [2, 4, 8, 16, 32])
    cases = [(v, 6.0) for v in sizes] + [
        (fixed_v, float(d)) for d in degrees if (fixed_v, float(d)) not in [(v, 6.0) for v in sizes]
    ]
    rows, graphs = [], []
    for v, deg in cases:
        g = random_graph(v, deg, seed=v + int(deg))
        e = len(g.edges)
        row = {"v": v, "e": e, "x": v + e}
        for name, fn in (("bfs", bfs_components), ("dfs", dfs_components)):
            counter = OpCounter()
            fn(g, counter)
            row[name + "_visits"] = counter.get("edge_visits")
            row[name + "_ms"] = best_time_ms(lambda fn=fn, g=g: fn(g))
        rows.append(row)
        graphs.append(g)
    rows.sort(key=lambda r: r["x"])
    out = [
        "\n### BFS / DFS scaling (seeded random graphs)\n",
        "Random graphs with V nodes and average degree d (E = V·d/2); first the V sweep at d = 6, then the d sweep at "
        f"V = {fixed_v:,}. `edge_visits` is the engine's own operation counter; time is the best of 5 runs of the traversal alone "
        "(graph already built), neighbours sorted by weight as in production.\n",
        "| V | E | V + E | BFS edge_visits | BFS ms | DFS edge_visits | DFS ms |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        out.append(
            f"| {r['v']:,} | {r['e']:,} | {r['x']:,} | {r['bfs_visits']:,} | {r['bfs_ms']:.2f} | {r['dfs_visits']:,} | {r['dfs_ms']:.2f} |"
        )
    xs = [r["x"] for r in rows]
    out += [
        "\nLeast-squares fits over all rows (x = V + E):\n",
        "| quantity | slope | intercept | R² |",
        "|---|---|---|---|",
    ]
    for label, key, unit in (
        ("BFS edge_visits", "bfs_visits", "per (V+E)"),
        ("DFS edge_visits", "dfs_visits", "per (V+E)"),
        ("BFS time", "bfs_ms", "ms per 10⁶ (V+E)"),
        ("DFS time", "dfs_ms", "ms per 10⁶ (V+E)"),
    ):
        slope, intercept, r2 = linear_fit(xs, [r[key] for r in rows])
        scale = 1e6 if "time" in label else 1
        out.append(f"| {label} | {slope * scale:.3f} {unit} | {intercept:.2f} | {r2:.4f} |")
    visits_fit = linear_fit([r["e"] for r in rows], [r["bfs_visits"] for r in rows])
    out.append(
        f"\nExactly 2E adjacency entries are scanned: BFS edge_visits vs E has slope {visits_fit[0]:.3f}, R² {visits_fit[2]:.4f}.\n"
    )
    chart = svg_chart(
        "BFS / DFS time vs. V + E",
        "V + E",
        "time (ms)",
        [
            {"name": "BFS", "points": [(r["x"], r["bfs_ms"]) for r in rows], "line": True},
            {"name": "DFS", "points": [(r["x"], r["dfs_ms"]) for r in rows], "line": True},
            {
                "name": "BFS edge_visits / 1000",
                "points": [(r["x"], r["bfs_visits"] / 1000) for r in rows],
                "line": True,
            },
        ],
    )
    (HERE / "graph_scaling.svg").write_text(chart)
    out.append("![BFS and DFS vs V+E](graph_scaling.svg)\n")

    # extra queue / stack space, measured with an instrumented replica of the engine traversals
    out += [
        "\n### Extra space: BFS queue vs. DFS stack (peak entries)\n",
        "Measured with instrumented copies of the engine traversals (the DFS copy is asserted to produce the "
        "engine's exact visit order). A node can be pushed on the DFS stack once per incident edge before it is "
        "popped, so the stack is bounded by O(E), while the BFS queue holds each node at most once, O(V).\n",
        "| graph | V | E | BFS queue peak | DFS stack peak | DFS peak / E |",
        "|---|---|---|---|---|---|",
    ]
    probes = [(f"complete K{n}", complete_graph(n)) for n in (8, 16, 32, 64)]
    probes += [
        (f"random d=6, V={g.nodes.__len__():,}", g)
        for g in graphs
        if len(g.nodes) in (sizes[0], sizes[-1]) and abs(len(g.edges) / len(g.nodes) - 3) < 0.1
    ]
    for label, g in probes:
        peak, order = dfs_peak_stack(g)
        assert order == dfs_components(g)[1], "instrumented DFS diverged from the engine"
        out.append(
            f"| {label} | {len(g.nodes):,} | {len(g.edges):,} | {bfs_peak_queue(g):,} | {peak:,} | {peak / max(1, len(g.edges)):.2f} |"
        )
    return "\n".join(out)


def complete_graph(n: int) -> FragmentGraph:
    rng = random.Random(n)
    nodes = [f"N{i:03d}" for i in range(n)]
    matches = [SideMatch(a, 1, b, 3, *([rng.random()] * 6)) for a, b in itertools.combinations(nodes, 2)]
    return build_graph(nodes, matches)


def svg_chart(title: str, xlabel: str, ylabel: str, series: list[dict], width: int = 640, height: int = 380) -> str:
    """Tiny dependency-free line/scatter chart (no matplotlib in the project)."""
    ml, mr, mt, mb = 64, 20, 36, 52
    xs = [x for s in series for x, _ in s["points"]]
    ys = [y for s in series for _, y in s["points"]]
    x0, x1, y0, y1 = min(xs), max(xs), 0.0, max(ys) * 1.05 or 1.0
    if x1 == x0:
        x1 = x0 + 1

    def px(x):
        return ml + (x - x0) / (x1 - x0) * (width - ml - mr)

    def py(y):
        return height - mb - (y - y0) / (y1 - y0) * (height - mt - mb)

    def fmt(v):
        return f"{v:.3g}" if abs(v) < 1000 else f"{v:,.0f}"

    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" font-family="sans-serif" font-size="12">',
        f'<rect width="{width}" height="{height}" fill="#ffffff"/>',
        f'<text x="{width / 2}" y="20" text-anchor="middle" font-size="14" font-weight="bold">{title}</text>',
    ]
    for i in range(6):
        gx, gy = x0 + (x1 - x0) * i / 5, y0 + (y1 - y0) * i / 5
        parts.append(f'<line x1="{px(gx):.1f}" y1="{mt}" x2="{px(gx):.1f}" y2="{height - mb}" stroke="#e5e7eb"/>')
        parts.append(f'<line x1="{ml}" y1="{py(gy):.1f}" x2="{width - mr}" y2="{py(gy):.1f}" stroke="#e5e7eb"/>')
        parts.append(
            f'<text x="{px(gx):.1f}" y="{height - mb + 16}" text-anchor="middle" fill="#374151">{fmt(gx)}</text>'
        )
        parts.append(f'<text x="{ml - 6}" y="{py(gy) + 4:.1f}" text-anchor="end" fill="#374151">{fmt(gy)}</text>')
    parts.append(
        f'<rect x="{ml}" y="{mt}" width="{width - ml - mr}" height="{height - mt - mb}" fill="none" stroke="#9ca3af"/>'
    )
    parts.append(f'<text x="{(ml + width - mr) / 2}" y="{height - 10}" text-anchor="middle">{xlabel}</text>')
    parts.append(
        f'<text x="14" y="{(mt + height - mb) / 2}" text-anchor="middle" transform="rotate(-90 14 {(mt + height - mb) / 2})">{ylabel}</text>'
    )
    for i, s in enumerate(series):
        color = COLORS[i % len(COLORS)]
        pts = " ".join(f"{px(x):.1f},{py(y):.1f}" for x, y in s["points"])
        if s.get("line"):
            parts.append(f'<polyline points="{pts}" fill="none" stroke="{color}" stroke-width="2"/>')
        for x, y in s["points"]:
            parts.append(f'<circle cx="{px(x):.1f}" cy="{py(y):.1f}" r="3.5" fill="{color}"/>')
        ly = mt + 16 + i * 16
        parts.append(f'<rect x="{ml + 10}" y="{ly - 9}" width="12" height="12" fill="{color}"/>')
        parts.append(f'<text x="{ml + 28}" y="{ly + 1}">{s["name"]}</text>')
    parts.append("</svg>\n")
    return "\n".join(parts)


def graph_report(quick: bool) -> str:
    threshold_md, _ = edges_vs_threshold(4 if quick else 5)
    return "\n".join(
        [
            GRAPH_BEGIN,
            "\n## Fragment graph (T14, `engine/graph.py`)\n",
            "Regenerate with `python validation/run_benchmarks.py --graph-only`. Counts, edge numbers and accuracies are "
            "deterministic; times are wall-clock and vary by machine.",
            threshold_md,
            traversal_scaling(quick),
            GRAPH_END,
            "",
        ]
    )


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--quick", action="store_true")
    p.add_argument("--node-limit", type=int, default=50_000)
    p.add_argument("--graph-only", action="store_true", help="only regenerate the fragment-graph section of results.md")
    args = p.parse_args()
    out = Path(__file__).with_name("results.md")
    if args.graph_only:
        report = graph_report(args.quick)
        text = out.read_text()
        if GRAPH_BEGIN in text:
            head, rest = text.split(GRAPH_BEGIN, 1)
            tail = rest.split(GRAPH_END, 1)[1].lstrip("\n") if GRAPH_END in rest else ""
            text = head + report + tail
        else:
            text = text.rstrip("\n") + "\n\n" + report
        out.write_text(text)
        print(report)
        return
    sizes = [3, 4] if args.quick else [3, 4, 5, 6]
    results = run(sizes, args.node_limit)
    body = f"""# RELIC-X — validation results

Generated by `validation/run_benchmarks.py` (node limit {args.node_limit:,}). Each cell is the mean over
the three bundled samples ({", ".join(SAMPLES)}). **acc.** = neighbour accuracy (share of true
adjacent pairs reconstructed correctly); **ms** = solver time only (matching excluded);
**\\*** = backtracking hit its node limit on at least one sample and returned its best-so-far.
{table(results, sizes)}

## Reading the tables

- Greedy scores each candidate against *all* placed neighbours, which makes it hard to beat on these inputs.
- Backtracking starts from the greedy solution and can only improve the total compatibility score.
  Higher score does not always mean higher accuracy when the matcher itself is wrong.
- Best-first (Prim) is the fastest; it trusts single strongest joins.
- Dijkstra minimises *path* cost from the seed, which is the wrong objective for assembly;
  it is kept as the comparison point (see docs/ALGORITHMS.md).

Owners: solver experiments **A**, matcher experiments **B** (T31, separate section to be added).

{graph_report(args.quick)}"""
    out.write_text(body)
    print(body)


if __name__ == "__main__":
    main()
