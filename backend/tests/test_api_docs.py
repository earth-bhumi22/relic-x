"""T41 — docs/API.md documents every operation the API exposes.

docs/API.md is generated by backend/scripts/gen_api_docs.py. If you add or rename
an endpoint, regenerate it; this test fails until you do.
"""

import re
from pathlib import Path

from relicx.core.config import Settings
from relicx.main import create_app

DOC = Path(__file__).resolve().parents[2] / "docs" / "API.md"


def test_every_operation_is_documented(tmp_path):
    app = create_app(Settings(database_url=f"sqlite:///{tmp_path}/d.db", storage_dir=str(tmp_path / "s")))
    text = DOC.read_text()
    missing = []
    for path, item in app.openapi()["paths"].items():
        for method in item:
            pattern = re.escape(path)
            pattern = re.sub(r"\\\{[a-z_]+\\\}", r"[^/`]+", pattern)  # {artifact_id} -> any placeholder
            if not re.search(rf"^### `{method.upper()} {pattern}`", text, re.M):
                missing.append(f"{method.upper()} {path}")
    assert not missing, f"not in docs/API.md (run scripts/gen_api_docs.py): {missing}"


def test_examples_contain_no_raw_ids():
    assert not re.search(r"\b[0-9a-f]{32}\b", DOC.read_text()), "an id was not replaced by a placeholder"
